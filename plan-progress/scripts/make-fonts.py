"""Cut the brand's two faces down to what the pane's SVG draws, and write hooks/lib/fonts.ts.

The pane's picture is an SVG the desktop draws in a frame of its own, where only fonts carried
inside the SVG can be used. This makes static instances of Heebo (Latin and Hebrew) and Cascadia
Mono (Latin), subsets them, and writes them as @font-face rules with data: URIs.

    python3 scripts/make-fonts.py HEEBO_LATIN.woff2 HEEBO_HEBREW.woff2 CASCADIA_LATIN.woff2

The inputs are the variable woff2 files Google Fonts serves (both faces are SIL OFL 1.1, see
fonts/OFL.txt). Needs fonttools and brotli.
"""
import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / 'hooks' / 'lib' / 'fonts.ts'

LATIN = 'U+0020-007E,U+00A0-00FF,U+2010-2027,U+2030-203A,U+2190-2193,U+2212'
HEBREW = 'U+0590-05FF,U+FB1D-FB4F'


def cut(path: str, weight: int, ranges: str) -> str:
    font = TTFont(path)
    if 'fvar' in font:
        axis = next(a for a in font['fvar'].axes if a.axisTag == 'wght')
        font = instancer.instantiateVariableFont(font, {'wght': max(axis.minValue, min(axis.maxValue, weight))})
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt', 'tnum', 'mark', 'mkmk', 'ccmp', 'locl']
    opts.name_IDs = [0, 13, 14]  # copyright and license; the subsets go by our own family names
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    unicodes = []
    for part in ranges.split(','):
        lo, _, hi = part.removeprefix('U+').partition('-')
        unicodes.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode('ascii')


def face(family: str, data: str, ranges: str) -> str:
    return (f"@font-face{{font-family:'{family}';src:url(data:font/woff2;base64,{data}) format('woff2');"
            f"unicode-range:{ranges};font-display:block}}")


def main() -> None:
    heebo_latin, heebo_hebrew, cascadia = sys.argv[1:4]
    rules = [
        face('pp-heebo', cut(heebo_latin, 850, LATIN), LATIN),
        face('pp-heebo', cut(heebo_hebrew, 850, HEBREW), HEBREW),
        face('pp-mono', cut(cascadia, 400, LATIN), LATIN),
    ]
    css = ''.join(rules)
    OUT.write_text(
        '// Generated by scripts/make-fonts.py: Heebo 850 (Latin, Hebrew) and Cascadia Mono 400 (Latin),\n'
        '// subset for the pane\'s SVG. SIL Open Font License 1.1, see fonts/OFL.txt. Do not edit.\n'
        f'export const FONT_FACES = {css!r}\n'
        "export const DISPLAY = \"'pp-heebo', Heebo, system-ui, sans-serif\"\n"
        "export const MONO = \"'pp-mono', 'Cascadia Mono', ui-monospace, Menlo, monospace\"\n",
        encoding='utf-8',
    )
    print(f'{OUT.relative_to(HERE)}: {len(css):,} characters of @font-face')


if __name__ == '__main__':
    main()
